# -*- coding: utf-8 -*-
import re


ADVISOR_SYSTEM_PROMPT = (
    "Ты — AiPulsar, персональный мудрый советник и аналитик рисков пользователя. "
    "При любом вопросе пользователя (финансы, покупки, кредиты, инвестиции, работа, договоры, "
    "повседневные решения или действия на ПК) ты обязан:\n"
    "1. Спокойно и объективно оценить возможные риски, скрытые комиссии, юридические или технические последствия.\n"
    "2. Предупредить о типичных ошибках, которые люди совершают в этой ситуации (включая защиту от мошенников и импульсивных трат).\n"
    "3. Предложить 2–3 взвешенных варианта действий с плюсами и минусами и порекомендовать самый безопасный и разумный шаг.\n"
    "Отвечай ясно, структурно, без воды и без навязывания, помогая человеку принять взвешенное решение."
)


class PulsarRiskAdvisor:
    """Локальный и облачный анализатор финансовых, бытовых и технических рисков."""

    FIN_KEYWORDS = (
        "кредит", "займ", "ипотек", "вложит", "инвест", "акци", "крипт", "бирж",
        "перевод", "перевест", "долг", "рассроч", "покупк", "купить", "продать",
        "деньг", "рубл", "доллар", "вклад", "депозит", "карт", "договор", "ставк",
    )

    SCAM_KEYWORDS = (
        "безопасный счет", "безопасный счёт", "код из смс", "сотрудник банка",
        "продиктовать код", "быстрый заработок", "гарантированный доход", "100% доход",
        "предоплат", "переведи на карту",
    )

    PC_RISK_KEYWORDS = (
        "удалить", "очистить", "форматировать", "реестр", "отключить защитник",
        "снести", "переустановить", "парол",
    )

    @classmethod
    def enrich_system_prompt(cls, base_prompt: str) -> str:
        if ADVISOR_SYSTEM_PROMPT in (base_prompt or ""):
            return base_prompt
        return f"{ADVISOR_SYSTEM_PROMPT}\n\n{base_prompt or ''}".strip()

    @classmethod
    def analyze_local_risk(cls, user_text: str) -> str:
        """Мгновенный локальный анализ рисков (работает даже без интернета)."""
        q = (user_text or "").strip().lower()
        if not q:
            return ""

        if any(k in q for k in cls.SCAM_KEYWORDS):
            return (
                "⚠️ ВНИМАНИЕ — ВЫСОКИЙ РИСК МОШЕННИЧЕСТВА:\n"
                "• Никогда не сообщайте коды из СМС и не переводите средства на «безопасные счета» — так действуют только мошенники.\n"
                "• Обещания «гарантированного высокого дохода» почти всегда ведут к полной потере средств.\n"
                "• Рекомендуемый шаг: прервите контакт, не переходите по сомнительным ссылкам и перепроверьте информацию по официальному номеру организации."
            )

        if any(k in q for k in cls.FIN_KEYWORDS):
            return (
                "🛡️ Финансовый советник AiPulsar — оценка рисков перед решением:\n"
                "1. Проверьте подушку безопасности: не стоит тратить или вкладывать последние средства (оставьте резерв минимум на 3–6 месяцев жизни).\n"
                "2. Оцените полную стоимость и худший сценарий: при кредите или покупке проверьте скрытые комиссии и переплату; при инвестициях — готовы ли вы к временной просадке капитала.\n"
                "3. Правило паузы 24 часов: перед крупной тратой или переводом возьмите паузу на сутки, сравните 2–3 альтернативы и внимательно прочитайте условия договора."
            )

        if any(k in q for k in cls.PC_RISK_KEYWORDS):
            return (
                "🛡️ Защита от ошибок на ПК (AiPulsar):\n"
                "• Перед удалением файлов или изменением настроек убедитесь, что важные документы сохранены в резервной копии.\n"
                "• Не отключайте системную защиту Windows при запуске файлов из непроверенных источников."
            )

        return ""
